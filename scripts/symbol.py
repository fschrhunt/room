"""symbol: build app/Assets.xcassets/room.sidebar.symbolset/room.sidebar.svg, the SF Symbols
template Finder shows on the share's sidebar row, from the 24x24 drawing assets/sidebar.svg.

assets/sidebar.svg is Apple's own SF Pro `folder` outline (the first path, in font units under its
transform) with the Room mark placed inside it. Following Apple's guidance for custom symbols, the
folder keeps the system symbol's exact size: every point is mapped back into SF Pro font units and
placed at the font's symbol scale, 100/2048 template units per unit, on the baseline. So the row's
icon matches Finder's native ones, and the mark keeps its place inside the folder. The same outline
fills the three variants actool needs (Ultralight, Regular and Black at small scale).
Run from the repository root after changing assets/sidebar.svg:  python3 scripts/symbol.py
"""
import re

SRC = "assets/sidebar.svg"
OUT = "app/Assets.xcassets/room.sidebar.symbolset/room.sidebar.svg"
UNIT = 100 / 2048  # template units per SF Pro font unit (cap height 1443 -> 70.459)
COLUMNS = {"Ultralight-S": 600.0, "Regular-S": 1500.0, "Black-S": 2400.0}
GUIDE = "fill:none;stroke:#27AAE1;stroke-width:0.5;"


def affine(transform):
    """(a, d, e, f) for a 'translate(..) scale(..)' transform: x' = a*x + e, y' = d*y + f."""
    a, d, e, f = 1.0, 1.0, 0.0, 0.0
    for name, args in re.findall(r"(translate|scale)\(([^)]*)\)", transform):
        v = [float(x) for x in re.split(r"[ ,]+", args.strip())]
        if name == "translate":
            e, f = e + a * v[0], f + d * (v[1] if len(v) > 1 else 0.0)
        else:
            a, d = a * v[0], d * (v[1] if len(v) > 1 else v[0])
    return a, d, e, f


def transform_path(data, point):
    """Rewrite absolute M/L/H/V/Q/C/Z path data through point(x, y); the source uses only these."""
    out, cur = [], (0.0, 0.0)
    for cmd, args in re.findall(r"([MLHVQCZ])([^MLHVQCZ]*)", data):
        nums = [float(n) for n in re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", args)]
        if cmd == "Z":
            out.append("Z")
            continue
        if cmd in "HV":
            for n in nums:
                cur = (n, cur[1]) if cmd == "H" else (cur[0], n)
                out.append("L%.3f %.3f" % point(*cur))
            continue
        pts = []
        for i in range(0, len(nums), 2):
            cur = (nums[i], nums[i + 1])
            pts.append("%.3f %.3f" % point(*cur))
        out.append(cmd + " ".join(pts))
    return " ".join(out)


source = open(SRC).read()
found = re.findall(r'<path[^>]*transform="([^"]+)"[^>]*\sd="([^"]+)"', source)
assert len(found) == 2, "expected the folder outline and the Room mark"
fa, fd, fe, ff = affine(found[0][0])  # the folder's transform: font units -> 24-unit drawing


def point_for(transform):
    """Maps a path's own coordinates to template units: drawing, then font units, then template."""
    a, d, e, f = affine(transform)

    def point(x, y):
        fx, fy = ((a * x + e) - fe) / fa, ((d * y + f) - ff) / fd
        return fx * UNIT, -fy * UNIT

    return point


paths = [transform_path(d, point_for(t)) for t, d in found]
glyph = "".join(f'\n      <path d="{p}"/>' for p in paths)
# The folder's advance, as in SF Pro: its side bearing (left edge of the outline) on both sides.
xs = [float(x) for x in re.findall(r"(-?[\d.]+) -?[\d.]+", paths[0])]
right = max(xs) + min(xs)
lines = [("Baseline-S", 696), ("Capline-S", 625.541), ("Baseline-M", 1126), ("Capline-M", 1055.54),
         ("Baseline-L", 1556), ("Capline-L", 1485.54)]
guides = "".join(f'\n    <line id="{n}" x1="263" x2="3036" y1="{y}" y2="{y}" style="{GUIDE}"/>' for n, y in lines)
guides += "".join(
    f'\n    <line id="{side}-margin-{n}" x1="{x + dx:.3f}" x2="{x + dx:.3f}" y1="600.785" y2="720.121" style="{GUIDE}"/>'
    for n, x in COLUMNS.items() for side, dx in (("left", 0.0), ("right", right)))
symbols = "".join(f'\n    <g id="{n}" transform="matrix(1 0 0 1 {x:.3f} 696)">{glyph}\n    </g>' for n, x in COLUMNS.items())

with open(OUT, "w") as out:
    out.write(f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!--Room sidebar symbol, generated by scripts/symbol.py from assets/sidebar.svg; edit that instead.-->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" width="3300" height="2200">
  <g id="Notes">
    <text id="template-version" x="2943" y="292" style="font-family:'SFProText-Regular';font-size:13px;">Template v.3.0</text>
  </g>
  <g id="Guides">{guides}
  </g>
  <g id="Symbols">{symbols}
  </g>
</svg>
''')
print(f"wrote {OUT}: folder at SF Pro's native symbol size")
