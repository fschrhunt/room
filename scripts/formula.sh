#!/bin/sh
# Writes room.rb, the Homebrew formula that installs a release's room script, from
# the release's checksums.txt. The release workflow runs it after publishing;
# room's repository is its own tap:
#
#   brew tap fschrhunt/room https://github.com/fschrhunt/room && brew install room
#
# usage: scripts/formula.sh vX.Y.Z CHECKSUMS > room.rb
set -eu
tag=$1
sums=$2
plain=${tag#v}
sha=$(grep " room-$plain.tar.gz\$" "$sums" | cut -d' ' -f1)
[ -n "$sha" ] || {
  echo "formula.sh: no checksum for room-$plain.tar.gz in $sums" >&2
  exit 1
}
cat <<RUBY
# frozen_string_literal: true

# Generated by scripts/formula.sh for each release; edit that script, not this file.
class Room < Formula
  desc "Mount an SMB share at login on macOS, the native way"
  homepage "https://github.com/fschrhunt/room"
  url "https://github.com/fschrhunt/room/releases/download/$tag/room-$plain.tar.gz"
  sha256 "$sha"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  def install
    bin.install "room"
  end

  def caveats
    <<~EOS
      Next: room add <smb://user@host/share>
    EOS
  end

  test do
    assert_equal "room $plain", shell_output("#{bin}/room version").strip
  end
end
RUBY
